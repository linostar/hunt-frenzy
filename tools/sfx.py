#!/usr/bin/env python3
"""Synthesises Hunt Frenzy's sound effects as 16-bit mono WAV.

Standard library only and fully deterministic (fixed seeds, no clock), so the committed
files can always be regenerated byte-for-byte. Synth core ported from BrewMagic's
tools/sfx.py (../jamference-20261016): one-pole low-pass, linear envelopes, piecewise
curves, peak-normalised 16-bit writer; a resonant band-pass (RBJ biquad) is added for the
rival's voice. Every sound is designed here from scratch: no sample, jingle or effect of
any other game is copied or imitated.

Sounds:
    <name>.wav              every game sound effect of EFFECTS (one generator each, its own
                            noise seed and peak level), played through Game.play_sfx(name);
                            the list is GameState.SFX_IDS (a test checks both agree).
    blurt_<timbre>_<vowel>.wav
                            one gibberish syllable of the rival's voice per timbre of
                            TIMBRES and vowel of VOWELS (a voiced source through two vowel
                            formants); Game.play_heckle strings them into a seeded blurt,
                            its pitch and timbre set by the heckle's category.

Every file is peak-normalised to its own level, never above PEAK, so nothing clips; the
levels set the mix, and --check holds each file's loudness as heard (loudness_of: BS.1770
K-weighting, the loudest 0.1 s) inside its kind's LOUDNESS_BANDS (events around the shot,
end-of-run stingers louder, menu sounds quieter), so no sound stands far above its siblings.
Each file's .import must exist (Godot imports it, so it ships).

Usage (from repo root):
    python3 tools/sfx.py           write every sound into huntfrenzy/audio/sfx/
    python3 tools/sfx.py --check   regenerate in memory and verify the committed files are
                                   byte-identical, imported, inside their loudness bands
                                   and none is stale; prints "sfx: OK"
"""
import io
import math
import random
import struct
import sys
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "huntfrenzy" / "audio" / "sfx"
RATE = 22050
PEAK = 0.9
# The rival's voice: syllables sit under the shots.
BLURT_PEAK = 0.5
BLURT_SECONDS = 0.11
BLURT_BASE_HZ = 150.0
TIMBRES = ("gruff", "nasal", "hoot")
# Vowel -> its first two formants in Hz.
VOWELS = {"a": (800.0, 1200.0), "e": (420.0, 2000.0), "o": (480.0, 820.0), "u": (330.0, 720.0)}
# The sound effects together must stay under this (all the audio stays under 8 MB: plan AC 15).
MAX_TOTAL_BYTES = 1024 * 1024


class SfxError(Exception):
    pass


def lowpass(samples, cutoffs):
    """One-pole low-pass filter with a per-sample cutoff in Hz."""
    out, y = [], 0.0
    for x, fc in zip(samples, cutoffs):
        y += (1.0 - math.exp(-2.0 * math.pi * fc / RATE)) * (x - y)
        out.append(y)
    return out


def bandpass(samples, centre, q):
    """RBJ biquad band-pass (constant 0 dB peak gain) at `centre` Hz with quality `q`."""
    w = 2 * math.pi * centre / RATE
    alpha = math.sin(w) / (2 * q)
    b0, b2, a0, a1, a2 = alpha, -alpha, 1 + alpha, -2 * math.cos(w), 1 - alpha
    out, x1, x2, y1, y2 = [], 0.0, 0.0, 0.0, 0.0
    for x in samples:
        y = (b0 * x + b2 * x2 - a1 * y1 - a2 * y2) / a0
        out.append(y)
        x2, x1, y2, y1 = x1, x, y1, y
    return out


def envelope(n, attack, release):
    """Linear attack, then linear release over the last `release` seconds."""
    a, r = max(1, int(attack * RATE)), max(1, int(release * RATE))
    return [min(1.0, i / a, (n - i) / r) for i in range(n)]


def lerp_curve(points, n):
    """Piecewise-linear curve through (time_fraction, value) points."""
    out = []
    for i in range(n):
        t = i / max(1, n - 1)
        for (t0, v0), (t1, v1) in zip(points, points[1:]):
            if t0 <= t <= t1:
                out.append(v0 + (v1 - v0) * (t - t0) / max(1e-9, t1 - t0))
                break
    return out


def oscillate(freqs, shape):
    """A wave following the per-sample frequency curve `freqs`; shape(phase 0..1) -> -1..1."""
    phase, out = 0.0, []
    for f in freqs:
        phase = (phase + f / RATE) % 1.0
        out.append(shape(phase))
    return out


def place(buf, samples, at, gain=1.0):
    """Adds `samples` into `buf` from `at` seconds on, growing `buf` as needed."""
    start = int(at * RATE)
    if len(buf) < start + len(samples):
        buf.extend([0.0] * (start + len(samples) - len(buf)))
    for i, s in enumerate(samples):
        buf[start + i] += s * gain
    return buf


def ping(freq, seconds, decay, partials=((1.0, 1.0),), attack=0.002):
    """A struck tone: sine partials (frequency multiple, amplitude) under an exponential decay."""
    n, a = int(seconds * RATE), max(1, int(attack * RATE))
    return [min(1.0, i / a) * math.exp(-decay * i / RATE)
            * sum(amp * math.sin(2 * math.pi * freq * mult * i / RATE) for mult, amp in partials if freq * mult < RATE / 2)
            for i in range(n)]


def sweep(start_hz, end_hz, seconds, shape, attack, release):
    """A tone gliding from start_hz to end_hz with a linear envelope."""
    n = int(seconds * RATE)
    raw = oscillate(lerp_curve([(0, start_hz), (1, end_hz)], n), shape)
    return [s * e for s, e in zip(raw, envelope(n, attack, release))]


def noise(seconds, rng, cutoffs, decay=0.0, attack=0.002, release=0.02):
    """Low-passed white noise; `cutoffs` is a lerp_curve point list for the cutoff in Hz."""
    n = int(seconds * RATE)
    raw = lowpass([rng.uniform(-1.0, 1.0) for _ in range(n)], lerp_curve(cutoffs, n))
    env = envelope(n, attack, release)
    return [s * e * math.exp(-decay * i / RATE) for i, (s, e) in enumerate(zip(raw, env))]


def highpassed(samples):
    """A first difference: keeps the bright part of a sound (clicks, scrapes)."""
    out, last = [], 0.0
    for x in samples:
        out.append(x - last)
        last = x
    return out


def thump(freq=110.0, seconds=0.16, drop=1.0, decay=18.0):
    """A low drum-like hit: a sine falling `drop` octaves fast, decaying."""
    n, phase, out = int(seconds * RATE), 0.0, []
    for i in range(n):
        phase += freq * (1.0 + drop * math.exp(-30.0 * i / RATE)) / RATE
        out.append(math.sin(2 * math.pi * phase) * math.exp(-decay * i / RATE))
    return out


def sine(p):
    return math.sin(2 * math.pi * p)


def square(p):
    return 1.0 if p < 0.5 else -1.0


def triangle(p):
    return 4.0 * abs(p - 0.5) - 1.0


def saw(p):
    return 2.0 * p - 1.0


def pulse(width):
    return lambda p: 1.0 if p < width else -width / (1.0 - width)


BELL = ((1.0, 1.0), (2.76, 0.35), (5.4, 0.15))
GLASS = ((1.0, 1.0), (2.4, 0.4))
# A plate of steel: strongly inharmonic partials.
STEEL = ((1.0, 1.0), (2.32, 0.7), (4.25, 0.45), (6.63, 0.3), (9.38, 0.18))
# A plucked string (the wave start and loss stingers echo the banjo of the music).
PLUCK = ((1.0, 1.0), (2.0, 0.6), (3.0, 0.35), (4.0, 0.2), (5.0, 0.12))


def note_hz(semitones_from_a4):
    return 440.0 * 2 ** (semitones_from_a4 / 12)


# Notes used below, as semitones from A4.
D4, G4, B4, D5, E5, G5, A5, B5, D6, G6, B6, D7 = -7, -2, 2, 5, 7, 10, 12, 14, 17, 22, 26, 29


def arpeggio(notes, gap, seconds, decay, partials):
    buf = []
    for i, semis in enumerate(notes):
        place(buf, ping(note_hz(semis), seconds, decay, partials), i * gap)
    return buf


def fx_shot(rng):
    """The player's shotgun: a sharp crack, a noise blast falling dark, a low boom."""
    buf = noise(0.42, rng, [(0, 9000), (0.08, 3000), (0.4, 900), (1, 300)], decay=9.0, attack=0.0005)
    place(buf, highpassed(noise(0.012, rng, [(0, 10000), (1, 10000)], attack=0.0002, release=0.006)), 0.0, 1.2)
    return place(buf, thump(70.0, 0.3, drop=1.5, decay=12.0), 0.0, 0.9)


def fx_empty_click(rng):
    """A shot with no shells: the hammer falling on an empty chamber, a dry double click."""
    buf = highpassed(noise(0.01, rng, [(0, 8000), (1, 5000)], attack=0.0002, release=0.006))
    place(buf, ping(2900.0, 0.03, 120.0, STEEL), 0.0, 0.35)
    place(buf, highpassed(noise(0.008, rng, [(0, 6000), (1, 4000)], attack=0.0002, release=0.005)), 0.045, 0.6)
    return place(buf, ping(2100.0, 0.025, 140.0, STEEL), 0.045, 0.25)


def fx_out_of_shells(rng):
    """The last shell fired (the pool is dry, the birds flee): a dull double buzz."""
    one = lowpass(sweep(150.0, 140.0, 0.08, square, 0.004, 0.03), [800.0] * int(0.08 * RATE))
    return place(list(one), one, 0.11)


def fx_hit(rng):
    """A bird hit: a soft thwack and a puff of feathers."""
    buf = thump(180.0, 0.1, drop=0.6, decay=30.0)
    place(buf, noise(0.22, rng, [(0, 5000), (0.3, 2500), (1, 900)], decay=14.0), 0.0, 0.7)
    return place(buf, highpassed(noise(0.03, rng, [(0, 7000), (1, 4000)])), 0.01, 0.5)


def fx_armored_clank(rng):
    """A pellet glancing off the armored goose's plate: a ringing steel clank."""
    buf = ping(820.0, 0.45, 9.0, STEEL, attack=0.0005)
    return place(buf, highpassed(noise(0.02, rng, [(0, 9000), (1, 6000)])), 0.0, 0.8)


def fx_armored_kill(rng):
    """The armored goose's last hit: a dented clank, then its plate crumpling."""
    buf = ping(640.0, 0.35, 12.0, STEEL, attack=0.0005)
    place(buf, noise(0.3, rng, [(0, 3500), (1, 700)], decay=10.0), 0.05, 0.8)
    return place(buf, thump(140.0, 0.16, drop=0.8), 0.04, 0.6)


def fx_split_pop(rng):
    """The splitter bursting into goslings: a cork pop and two chirps flying apart."""
    buf = place(thump(320.0, 0.06, drop=1.5, decay=50.0), highpassed(noise(0.02, rng, [(0, 6000), (1, 3000)])), 0.0, 0.6)
    place(buf, sweep(1300.0, 2100.0, 0.07, triangle, 0.003, 0.04), 0.06, 0.45)
    return place(buf, sweep(1500.0, 2500.0, 0.07, triangle, 0.003, 0.04), 0.11, 0.4)


def fx_golden_chime(rng):
    """The golden goose shot: a bright rising sparkle of bells."""
    buf = arpeggio([G6, B6, D7, G6 + 12], 0.055, 0.4, 9.0, BELL)
    for at, f in ((0.03, 4200.0), (0.1, 5100.0), (0.17, 4700.0)):
        place(buf, ping(f, 0.12, 30.0, GLASS), at, 0.25)
    return buf


def fx_decoy_penalty(rng):
    """The protected pigeon shot: a falling, wobbling "wah-wah" of disapproval."""
    buf = []
    for i, (start, end) in enumerate(((330.0, 300.0), (260.0, 200.0))):
        n = int(0.24 * RATE)
        freqs = [(start + (end - start) * j / n) * (1.0 + 0.03 * math.sin(2 * math.pi * 9.0 * j / RATE)) for j in range(n)]
        tone = lowpass(oscillate(freqs, square), [1100.0] * n)
        place(buf, [s * e for s, e in zip(tone, envelope(n, 0.01, 0.1))], i * 0.25)
    return buf


def fx_escape(rng):
    """A bird getting away: a rising whoosh of wings."""
    n = int(0.45 * RATE)
    buf = noise(0.45, rng, [(0, 500), (0.7, 2600), (1, 3200)], attack=0.08, release=0.15)
    return [s * (0.6 + 0.4 * math.sin(2 * math.pi * 14.0 * i / RATE)) for i, s in enumerate(buf[:n])]


