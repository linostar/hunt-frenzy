def fx_time_up(rng):
    """Time Attack's time running out: a buzzer."""
    n = int(0.8 * RATE)
    raw = lowpass(oscillate([196.0 * (1.0 + 0.004 * math.sin(2 * math.pi * 30.0 * i / RATE)) for i in range(n)], saw), [2200.0] * n)
    raw2 = lowpass(oscillate([247.0] * n, square), [1600.0] * n)
    return [(a + 0.5 * b) * e for a, b, e in zip(raw, raw2, envelope(n, 0.01, 0.12))]


